/** 화면 글자 모양. 문자열 자리는 string, 함수 자리는 같은 인자의 함수. */
type Widen<T> = T extends string
  ? string
  : T extends (...args: infer A) => string
    ? (...args: A) => string
    : { [K in keyof T]: Widen<T[K]> };
export type Messages = Widen<typeof ko>;
